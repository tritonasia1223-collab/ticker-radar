// 그 해(1.1~12.31)에 재임한 사람들을 취임 순서로. 연말에 물러난 사람과 연초에 온 사람이 같은 해에 겹치면 "전임→후임".
function namesInYear(tenures: Tenure[], year: number): string[] {
  const start = `${year}-01-01`, end = `${year}-12-31`;
  const names: string[] = [];
  for (const t of tenures) {
    if (t.from > end) break;
    if (t.to !== null && t.to < start) continue;
    if (names[names.length - 1] !== t.name) names.push(t.name);
  }
  return names;
}

export function leadersForYear(year: number): { president: string; fed: string } | null {
  if (!Number.isFinite(year) || year < 1789) return null;
  const president = namesInYear(PRESIDENTS, year).join("→");
  const fedNames = namesInYear(FED_CHAIRS, year);
  return { president, fed: fedNames.length ? fedNames.join("→") : "—" };
}
